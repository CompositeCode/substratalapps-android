package com.substratalapps.hub.model

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import java.io.File

@Serializable
private data class CatalogExport(
    val apiVersion: String,
    val specVersion: String,
    val screens: List<ScreenEntry>,
)

@Serializable
private data class ScreenEntry(val spec: ScreenSpec, val buildState: BuildState, val navRoute: String)

/**
 * This app's entry for the Substratal Hub help center (`help/apps/android.json` in
 * substratalapps-applications-specs). Lists the design-package screens the app has built; any
 * screen not listed is planned. Deterministic, so an unchanged app produces an identical file.
 */
@Serializable
private data class HelpStatus(
    @SerialName("\$description") val description: String,
    val platform: String,
    val app: String,
    @SerialName("app_version") val appVersion: String,
    @SerialName("api_version") val apiVersion: String,
    val screens: Map<String, String>,
)

/**
 * Writes `<dir>/screens.json` (the full catalog, for the API coverage check) and
 * `<dir>/android.json` (build status for the help center). Args: <dir> <appVersion>.
 */
fun main(args: Array<String>) {
    val dir = File(args.getOrElse(0) { "build/help" }).apply { mkdirs() }
    val appVersion = args.getOrElse(1) { "0.0.0" }
    val json = Json { prettyPrint = true; encodeDefaults = true }

    File(dir, "screens.json").writeText(
        json.encodeToString(
            CatalogExport.serializer(),
            CatalogExport(
                ApiVersioning.CURRENT,
                ApiVersioning.SPEC_VERSION,
                ScreenCatalog.all.map { ScreenEntry(it, ImplementationStatus.of(it.id), it.navRoute) },
            ),
        ),
    )

    // Only design-package screens: the help center's IDs. Screens this app proposes on its own
    // (Phase.PROPOSED) aren't in the specs, so they have no help page to report on.
    val built = ScreenCatalog.all
        .filter { it.phase != Phase.PROPOSED }
        .map { it.id to ImplementationStatus.of(it.id) }
        .filter { (_, state) -> state != BuildState.PLANNED }
        .sortedBy { it.first }
        .associate { (id, state) -> id to state.name.lowercase() }
    File(dir, "android.json").writeText(
        json.encodeToString(
            HelpStatus.serializer(),
            HelpStatus(
                description = "Screens the Android app has built. Generated by CompositeCode/substratalapps-android " +
                    "(./gradlew :core:model:exportHelp); don't edit by hand. Screens not listed are planned.",
                platform = "android",
                app = "CompositeCode/substratalapps-android",
                appVersion = appVersion,
                apiVersion = ApiVersioning.CURRENT,
                screens = built,
            ),
        ) + "\n",
    )
    println("Wrote ${ScreenCatalog.all.size} screens and ${built.size} built-screen statuses to $dir")
}
